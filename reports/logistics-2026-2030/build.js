// data table
const TBL = (headers, rows, widths, opts = {}) => {
  const sum = widths.reduce((a, b) => a + b, 0);
  if (sum !== W) throw new Error(`widths must sum to ${W}, got ${sum}`);
  const hdr = new TableRow({
    tableHeader: true,
    children: headers.map((h, i) =>
      new TableCell({
        width: { size: widths[i], type: WidthType.DXA },
        shading: { type: ShadingType.CLEAR, fill: NAVY },
        margins: { top: 90, bottom: 90, left: 110, right: 110 },
        children: [new Paragraph({ spacing: { line: 260 }, alignment: AlignmentType.CENTER, children: [new TextRun({ text: h, bold: true, size: 19, color: "FFFFFF" })] })],
      })
    ),
  });
  const body = rows.map((r, ri) =>
    new TableRow({
      children: r.map((c, i) =>
        new TableCell({
          width: { size: widths[i], type: WidthType.DXA },
          shading: { type: ShadingType.CLEAR, fill: ri % 2 ? "F7F9FC" : "FFFFFF" },
          margins: { top: 90, bottom: 90, left: 110, right: 110 },
          children: String(c).split("|").map((line, li) =>
            new Paragraph({
              spacing: { line: 260, after: li === String(c).split("|").length - 1 ? 0 : 40 },
              alignment: opts.center && i > 0 ? AlignmentType.CENTER : AlignmentType.LEFT,
              children: [new TextRun({ text: line, size: 19, bold: opts.boldFirstCol && i === 0 })],
            })
          ),
        })
      ),
    })
  );
  return new Table({
    columnWidths: widths,
    width: { size: W, type: WidthType.DXA },
    borders: {
      top: { style: BorderStyle.SINGLE, size: 4, color: "BFBFBF" },
      bottom: { style: BorderStyle.SINGLE, size: 4, color: "BFBFBF" },
      left: { style: BorderStyle.SINGLE, size: 4, color: "BFBFBF" },
      right: { style: BorderStyle.SINGLE, size: 4, color: "BFBFBF" },
      insideHorizontal: { style: BorderStyle.SINGLE, size: 2, color: "D9D9D9" },
      insideVertical: { style: BorderStyle.SINGLE, size: 2, color: "D9D9D9" },
    },
    rows: [hdr, ...body],
  });
};

